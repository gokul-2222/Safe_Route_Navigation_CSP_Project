export function getTranslation(key, lang = AppState.currentLanguage) {
    if (translations[lang] && translations[lang][key]) {
        return translations[lang][key];
    }
    return translations['en'][key] || key;
}

export function setLanguage(lang) {
    if (translations[lang]) {
        AppState.currentLanguage = lang;
        return true;
    }
    return false;
}

export function getCurrentLanguage() {
    return AppState.currentLanguage;
}

export function translatePage(lang = AppState.currentLanguage) {
    setLanguage(lang);
    
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translatedText = getTranslation(key, lang);
        
        if (el.tagName === 'INPUT' && (el.type === 'text' || el.type === 'tel')) {
            el.placeholder = translatedText;
        } else {
            const icon = el.querySelector('i');
            if (icon) {
                el.innerHTML = '';
                el.appendChild(icon);
                
                const span = document.createElement('span');
                span.innerText = ' ' + translatedText;
                el.appendChild(span);
            } else {
                el.innerText = translatedText;
            }
        }
    });
}
